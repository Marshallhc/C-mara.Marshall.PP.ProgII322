package parcial1rescateanimal;

/**
 * Enumerado que representa el estado de salud de un animal alojado
 * en el Centro de Rescate.
 */
public enum EstadoSalud {
    /** El animal está en riesgo y requiere atención inmediata. */
    CRITICO,
    /** El animal está en tratamiento y mejorando. */
    EN_RECUPERACION,
    /** El animal está estable. */
    ESTABLE
}
